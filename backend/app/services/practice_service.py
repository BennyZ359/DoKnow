"""Practice service (whitepaper §13.2 module 7) — the 练 of 学练用讲温.

Exercises are generated by the Exercise Generator agent but graded here:
objective questions (single choice / true-false) are graded deterministically,
subjective ones (short answer / code) are recorded as pending and graded by
the assessment engine workflow later. Every graded attempt feeds the mastery
state machine through assessment_service (完成不等于掌握).
"""

from __future__ import annotations

import uuid

import structlog
from sqlalchemy import select

from app.core.database import SessionLocal
from app.core.events import EventType, bus, utcnow
from app.models.practice import Exercise, ExerciseAttempt, QuestionType
from app.services import assessment_service, memory_service

logger = structlog.get_logger("app.services.practice")

# Question types the system can grade without a model.
OBJECTIVE_TYPES = {QuestionType.SINGLE_CHOICE.value, QuestionType.TRUE_FALSE.value}


class PracticeServiceError(Exception):
    pass


class ExerciseNotFoundError(PracticeServiceError):
    pass


# ---------------------------------------------------------------------------
# Exercise bank
# ---------------------------------------------------------------------------


def save_exercises(
    knowledge_point_id: uuid.UUID,
    questions: list[dict],
    *,
    task_id: uuid.UUID | None = None,
) -> list[str]:
    """Persist LLM-generated questions. Returns created exercise ids."""
    ids: list[str] = []
    with SessionLocal() as db:
        for q in questions:
            qtype = QuestionType(q.get("question_type") or "SINGLE_CHOICE")
            exercise = Exercise(
                task_id=task_id,
                knowledge_point_id=knowledge_point_id,
                question_type=qtype,
                prompt=str(q.get("question") or "")[:10000],
                content={
                    "options": [str(o) for o in (q.get("options") or [])],
                    "answer": str(q.get("answer") or ""),
                    "explanation": str(q.get("explanation") or ""),
                    "difficulty": q.get("difficulty") or "BEGINNER",
                },
                difficulty=_difficulty_to_float(q.get("difficulty")),
            )
            db.add(exercise)
            ids.append(exercise.id)  # flushed on commit; id already set by default
        db.commit()
    logger.info("practice.exercises_saved", kp=str(knowledge_point_id), count=len(ids))
    return [str(i) for i in ids]


def get_exercises(
    knowledge_point_id: uuid.UUID, *, active_only: bool = True, limit: int = 10
) -> list[dict]:
    with SessionLocal() as db:
        stmt = (
            select(Exercise)
            .where(Exercise.knowledge_point_id == knowledge_point_id)
            .order_by(Exercise.created_at)
            .limit(limit)
        )
        if active_only:
            stmt = stmt.where(Exercise.is_active.is_(True))
        rows = db.scalars(stmt).all()
        return [_exercise_to_dict(e) for e in rows]


def count_exercises(knowledge_point_id: uuid.UUID) -> int:
    with SessionLocal() as db:
        return (
            db.scalar(
                select(Exercise.id)
                .where(
                    Exercise.knowledge_point_id == knowledge_point_id,
                    Exercise.is_active.is_(True),
                )
                .limit(1)
            )
            is not None
        )


def get_exercise_full(exercise_id: uuid.UUID) -> dict | None:
    """Exercise including the stored answer — grading/assessment use only."""
    with SessionLocal() as db:
        exercise = db.get(Exercise, exercise_id)
        if not exercise:
            return None
        content = exercise.content or {}
        return {
            "id": exercise.id,
            "knowledge_point_id": exercise.knowledge_point_id,
            "question_type": exercise.question_type.value if exercise.question_type else None,
            "prompt": exercise.prompt,
            "options": content.get("options") or [],
            "answer": content.get("answer") or "",
            "explanation": content.get("explanation") or "",
        }


def get_attempt(attempt_id: uuid.UUID) -> dict | None:
    with SessionLocal() as db:
        attempt = db.get(ExerciseAttempt, attempt_id)
        if not attempt:
            return None
        return {
            "id": attempt.id,
            "exercise_id": attempt.exercise_id,
            "task_id": attempt.task_id,
            "user_answer": attempt.user_answer or {},
            "is_correct": attempt.is_correct,
            "score": attempt.score,
            "feedback": attempt.feedback or {},
        }


