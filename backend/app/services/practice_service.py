def record_attempt(
    *,
    user_id: uuid.UUID,
    goal_id: uuid.UUID,
    exercise_id: uuid.UUID,
    answer: dict,
    task_id: uuid.UUID | None = None,
) -> dict:
    """Record one submission. Objective questions grade immediately and fold
    into mastery; subjective ones wait for the AI grader (pending_grading)."""
    with SessionLocal() as db:
        exercise = db.get(Exercise, exercise_id)
        if not exercise:
            raise ExerciseNotFoundError(str(exercise_id))
        objective = (
            exercise.question_type.value in OBJECTIVE_TYPES if exercise.question_type else False
        )
        is_correct = _grade_objective(exercise, answer) if objective else None
        score = (1.0 if is_correct else 0.0) if is_correct is not None else None
        attempt = ExerciseAttempt(
            exercise_id=exercise_id,
            task_id=task_id,
            user_answer=answer,
            is_correct=is_correct,
            score=score,
            mastery_estimate=(0.75 if is_correct else 0.25) if is_correct is not None else None,
            feedback={} if is_correct is not None else {"status": "pending_grading"},
            attempted_at=utcnow(),
        )
        db.add(attempt)
        db.commit()
        kp_id = exercise.knowledge_point_id
        attempt_id = attempt.id
        qtype = exercise.question_type.value if exercise.question_type else None

    memory_service.record_event(
        user_id=user_id,
        goal_id=goal_id,
        subject_type="ExerciseAttempt",
        subject_id=attempt_id,
        event_name="exercise.attempted",
        payload={
            "exercise_id": str(exercise_id),
            "knowledge_point_id": str(kp_id),
            "question_type": qtype,
            "is_correct": is_correct,
        },
    )
    bus.publish(
        EventType.EXERCISE_ATTEMPTED,
        aggregate_id=attempt_id,
        aggregate_type="ExerciseAttempt",
        payload={"knowledge_point_id": str(kp_id), "is_correct": is_correct},
    )
    if is_correct is not None:
        assessment_service.record_assessment(
            user_id=user_id,
            goal_id=goal_id,
            knowledge_point_id=kp_id,
            assessment_type="EXERCISE",
            score=score,
            confidence=0.85,
            result={"attempt_id": str(attempt_id), "question_type": qtype},
        )
    return {
        "attempt_id": str(attempt_id),
        "is_correct": is_correct,
        "score": score,
        "status": "graded" if is_correct is not None else "pending_grading",
    }


def record_subjective_grade(
    *,
    user_id: uuid.UUID,
    goal_id: uuid.UUID,
    attempt_id: uuid.UUID,
    score: float,
    confidence: float,
    feedback: dict,
) -> dict:
    """Fold an AI grader's verdict into a pending subjective attempt."""
    with SessionLocal() as db:
        attempt = db.get(ExerciseAttempt, attempt_id)
        if not attempt:
            raise ExerciseNotFoundError(str(attempt_id))
        exercise = db.get(Exercise, attempt.exercise_id)
        attempt.score = max(0.0, min(1.0, float(score)))
        attempt.is_correct = attempt.score >= 0.8
        attempt.mastery_estimate = attempt.score
        attempt.feedback = {**(attempt.feedback or {}), **feedback, "status": "graded"}
        db.commit()
        kp_id = exercise.knowledge_point_id
        qtype = exercise.question_type.value if exercise.question_type else None
    assessment_service.record_assessment(
        user_id=user_id,
        goal_id=goal_id,
        knowledge_point_id=kp_id,
        assessment_type="EXERCISE",
        score=attempt.score,
        confidence=max(0.0, min(1.0, float(confidence))),
        result={"attempt_id": str(attempt_id), "question_type": qtype, "ai_graded": True},
    )
    return {"attempt_id": str(attempt_id), "score": attempt.score, "status": "graded"}


def _grade_objective(exercise: Exercise, answer: dict) -> bool | None:
    """Deterministic grading: exact (normalized) answer match."""
    expected = str((exercise.content or {}).get("answer") or "").strip()
    if not expected:
        return None  # cannot grade without a stored answer
    submitted = str(
        answer.get("choice") or answer.get("answer") or answer.get("value") or ""
    ).strip()
    return submitted == expected


def _exercise_to_dict(e: Exercise) -> dict:
    content = e.content or {}
    return {
        "id": e.id,
        "knowledge_point_id": e.knowledge_point_id,
        "question_type": e.question_type.value if e.question_type else None,
        "prompt": e.prompt,
        "options": content.get("options") or [],
        "difficulty": content.get("difficulty") or "BEGINNER",
        # answer/explanation are NOT exposed until the learner has attempted
        "has_answer": bool(content.get("answer")),
    }


def _difficulty_to_float(value) -> float:
    return {"BEGINNER": 0.3, "INTERMEDIATE": 0.5, "ADVANCED": 0.8}.get(str(value or ""), 0.5)
